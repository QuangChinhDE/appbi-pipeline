export const CATALOGS: Record<Locale, Catalog> = { vi, en };

/**
 * Endonyms. A language switcher names each language in that language, so these
 * are deliberately not translated and do not belong in the catalogs.
 */
export const LOCALE_NAMES: Record<Locale, string> = {
  vi: 'Tiếng Việt',
  en: 'English',
};

export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const raw = CATALOGS[locale][key] ?? CATALOGS.vi[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

/** Keys present in `vi` but missing from `en`; used by the i18n coverage test. */
export function missingTranslations(): string[] {
  return Object.keys(vi).filter((key) => !(key in en));
}
